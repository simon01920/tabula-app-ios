#!/usr/bin/env bash
# Fetch llama.cpp at a pinned release tag into LlamaSpike/Sources/CLlama/upstream (sparse checkout:
# only the files the SwiftPM C/C++ target compiles), then generate what CMake would normally generate:
#   - generated/llama-version.h, generated/ggml-version.h
#   - include/*.h  symlinks to the upstream public headers (SwiftPM publicHeadersPath; symlinks, not
#                  copies, so clang's #pragma once de-duplicates by inode)
#   - generated/metal/*.metal + generated/ggml-metal-embed.S  (GGML_METAL_EMBED_LIBRARY: Metal *source*
#                  text embedded via .incbin and compiled at runtime with newLibraryWithSource; Apple-only,
#                  the .S is empty on Linux)
# The upstream tree is never committed to the Tabula repo (see ../.gitignore).
set -euo pipefail

LLAMA_TAG="${LLAMA_TAG:-b11382}"
LLAMA_COMMIT_EXPECTED="${LLAMA_COMMIT_EXPECTED:-11fe02151f79c41d0d4af7da708755d73b9c0da6}"
LLAMA_REPO="${LLAMA_REPO:-https://github.com/ggml-org/llama.cpp}"

PKG_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../LlamaSpike" && pwd)"
T="$PKG_DIR/Sources/CLlama"
UP="$T/upstream"
GEN="$T/generated"
INC="$T/include"

echo "== fetch $LLAMA_REPO @ $LLAMA_TAG -> $UP"
rm -rf "$UP" "$GEN"
git -c advice.detachedHead=false clone --quiet --depth 1 --filter=blob:none --sparse \
    --branch "$LLAMA_TAG" "$LLAMA_REPO" "$UP"
# Only the CPU + Metal backends (no CUDA/Vulkan/SYCL/... trees), plus one vocab-only GGUF (tokenizer
# data, no weights) used by the probe to exercise the GBNF grammar sampler without downloading a model.
git -C "$UP" sparse-checkout set --no-cone \
    '/LICENSE' '/include/' '/src/' '/ggml/include/' \
    '/ggml/src/*.c' '/ggml/src/*.cpp' '/ggml/src/*.h' \
    '/ggml/src/ggml-cpu/' '/ggml/src/ggml-metal/' \
    '/models/ggml-vocab-qwen2.gguf'
COMMIT="$(git -C "$UP" rev-parse HEAD)"
if [ "$COMMIT" != "$LLAMA_COMMIT_EXPECTED" ]; then
    echo "ERROR: $LLAMA_TAG resolved to $COMMIT, expected $LLAMA_COMMIT_EXPECTED" >&2
    exit 1
fi
SHORT="${COMMIT:0:7}"
printf '%s %s\n' "$LLAMA_TAG" "$COMMIT" > "$T/UPSTREAM_PIN"
rm -rf "$UP/.git"   # keep SwiftPM's directory walk small; provenance is in UPSTREAM_PIN

# Upstream build-system files we do not use (SwiftPM would otherwise warn about unhandled files).
find "$UP" -name 'CMakeLists.txt' -delete
find "$UP" \( -name '*.cmake' -o -name '*.in' -o -name '*.md' \) -delete

# Version strings (CMake: configure_file of *-version.h.in). GGML_VERSION from ggml/CMakeLists.txt is not
# in the sparse checkout, so take it from the upstream release metadata we pin here.
GGML_VERSION="${GGML_VERSION:-0.25.3}"
LLAMA_VERSION="${LLAMA_VERSION:-0.5.0-dev}"
mkdir -p "$GEN/metal"
cat > "$GEN/llama-version.h" <<EOF
#pragma once
#define LLAMA_VERSION "$LLAMA_VERSION"
#define LLAMA_COMMIT  "$SHORT"
EOF
cat > "$GEN/ggml-version.h" <<EOF
#pragma once
#define GGML_VERSION "$GGML_VERSION"
#define GGML_COMMIT  "$SHORT"
EOF

# Public headers for Swift clients (module.modulemap in include/ is committed; headers are symlinks).
find "$INC" -maxdepth 1 -name '*.h' -delete
ln -s ../upstream/include/llama.h "$INC/llama.h"
for h in "$UP"/ggml/include/*.h; do
    ln -s "../upstream/ggml/include/$(basename "$h")" "$INC/$(basename "$h")"
done

# Embedded Metal library (mirrors ggml/src/ggml-metal/CMakeLists.txt, GGML_METAL_EMBED_LIBRARY=ON).
MSRC="$UP/ggml/src/ggml-metal"
KERNELS_COMMON="$MSRC/kernels/common.h"
KERNELS_DEQ="$MSRC/kernels/dequantize.h"
KERNELS_Q="$MSRC/kernels/quantize.h"
FA_COMMON="$MSRC/kernels/fa_common.metal"
FA_VEC_COMMON="$MSRC/kernels/fa_vec_common.metal"
GGML_COMMON="$UP/ggml/src/ggml-common.h"
METAL_IMPL="$MSRC/ggml-metal-impl.h"
# Kind list = the X(...) table in ggml-metal-device.m (single source of truth upstream).
KINDS="$(sed -n '/^#define GGML_METAL_LIBS/,/^$/p' "$MSRC/ggml-metal-device.m" \
         | grep -o 'X([A-Z0-9_]*, *[a-z0-9_]*)' | sed -E 's/X\([A-Z0-9_]*, *([a-z0-9_]*)\)/\1/')"
ASM="$GEN/ggml-metal-embed.S"
{
    echo "// generated by fetch-llama.sh from llama.cpp $LLAMA_TAG ($SHORT) -- do not edit"
    echo "#if defined(__APPLE__)"
} > "$ASM"
n=0
for kind in $KINDS; do
    src="$MSRC/kernels/$kind.metal"
    [ -f "$src" ] || { echo "ERROR: missing kernel source $src" >&2; exit 1; }
    hdrs=("$KERNELS_COMMON")
    grep -q '#include "dequantize\.h"' "$src" && hdrs+=("$KERNELS_DEQ")
    grep -q '#include "quantize\.h"' "$src" && hdrs+=("$KERNELS_Q")
    grep -q '#include "fa_common\.metal"' "$src" && hdrs+=("$FA_COMMON")
    grep -q '#include "fa_vec_common\.metal"' "$src" && hdrs+=("$FA_VEC_COMMON")
    out="$GEN/metal/ggml-metal-embed-$kind.metal"
    cat "${hdrs[@]}" "$src" \
      | sed -e '/#include "common.h"/d' -e '/#include "dequantize.h"/d' -e '/#include "quantize.h"/d' \
            -e '/#include "fa_common.metal"/d' -e '/#include "fa_vec_common.metal"/d' -e '/#pragma once/d' \
      | sed -e "/__embed_ggml-common.h__/r $GGML_COMMON" -e '/__embed_ggml-common.h__/d' \
      | sed -e "/#include \"ggml-metal-impl.h\"/r $METAL_IMPL" -e '/#include "ggml-metal-impl.h"/d' \
      > "$out"
    {
        echo ".section __DATA,__ggml_metallib"
        echo ".globl _ggml_metallib_${kind}_start"
        echo "_ggml_metallib_${kind}_start:"
        echo ".incbin \"$out\""
        echo ".globl _ggml_metallib_${kind}_end"
        echo "_ggml_metallib_${kind}_end:"
    } >> "$ASM"
    n=$((n + 1))
done
echo "#endif" >> "$ASM"

echo "pinned:   $LLAMA_TAG $COMMIT"
echo "sources:  $(find "$UP" -type f \( -name '*.c' -o -name '*.cpp' -o -name '*.m' \) | wc -l) C/C++/ObjC files"
echo "headers:  $(ls "$INC"/*.h | wc -l) public header symlinks"
echo "metal:    $n embedded kernel sources ($(du -sh "$GEN/metal" | cut -f1)) -> $ASM"
