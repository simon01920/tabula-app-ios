// swift-tools-version: 6.0
// Root SwiftPM package for the LOCAL xtool build path (see xtool.yml).
// xtool requires each app/extension to be an *automatic* library product of this root package;
// it generates a stub executable per product and links it (Sources/PackLib/Planner.swift + Packer.swift).
// The CI path (project.yml / XcodeGen) compiles the SAME source folders: App/Sources, WidgetExtension/Sources,
// and the same local packages. Keep both in sync; scripts/validate.sh checks the folder mapping.
import PackageDescription

// Macro isolation (CLAUDE.md rule 5): the default app build uses NO Swift macros, so one unsupported
// macro under xtool cannot block every device check. Setting TABULA_MACRO_PROBES=1 in the environment
// when the manifest is evaluated compiles the macro-probe variant (@Observable, @Entry, @State, @Generable).
// Used by `scripts/xtool-dev.sh --macro-probes`. The XcodeGen/CI path always defines it (project.yml).
let macroProbes = Context.environment["TABULA_MACRO_PROBES"] == "1"

// Cross-import overlays (e.g. `_PhotosUI_SwiftUI` = PhotosPicker/PhotosPickerItem, `_StoreKit_SwiftUI`,
// `_AppIntents_SwiftUI`, `_MapKit_SwiftUI`) are what make `import PhotosUI` + `import SwiftUI` expose the
// SwiftUI APIs. Xcode enables them implicitly; xtool 1.20.1's SwiftBuild toolset (toolset-swb.json) does not
// (its legacy toolset.json does). VERIFIED 2026-10-06: without this flag `xtool dev build` fails with
// "cannot find type 'PhotosPickerItem' in scope". Root package only, so unsafeFlags are permitted.
let crossImportOverlays: [SwiftSetting] = [.unsafeFlags(["-Xfrontend", "-enable-cross-import-overlays"])]

// App Intents UI (Phase 4 B3): `TABULA_APP_INTENTS` turns on the intent-driven controls (Homework widget checkbox,
// loud-alarm "Done", configurable Now & Next / Today). They need `Metadata.appintents`, which only Xcode generates
// (RISKS #19), so project.yml always defines it and this xtool manifest does NOT by default: xtool builds keep the
// link / Snooze / static fallbacks. TABULA_APP_INTENTS=1 in the environment compiles them anyway, for the on-device
// experiment "what does a metadata-less intent control do?" (docs/checklists/PHASE4_DEVICE.md B3.X1).
let appIntentsUI = Context.environment["TABULA_APP_INTENTS"] == "1"
let intentDefines: [SwiftSetting] = appIntentsUI ? [.define("TABULA_APP_INTENTS")] : []
// iCloud sync (Phase 6 S1): project.yml defines TABULA_CLOUDKIT only with the paid entitlements. TABULA_CLOUDKIT=1 here
// is a COMPILE CHECK only (`xtool-dev.sh --cloudkit` refuses to install: CKContainer traps without the entitlement).
let cloudKitDefines: [SwiftSetting] = Context.environment["TABULA_CLOUDKIT"] == "1" ? [.define("TABULA_CLOUDKIT")] : []
let appSwiftSettings: [SwiftSetting] = crossImportOverlays + (macroProbes ? [.define("TABULA_MACRO_PROBES")] : [])
    + intentDefines + cloudKitDefines

let package = Package(
    name: "Tabula",
    platforms: [
        .iOS("26.0"),
    ],
    products: [
        .library(name: "TabulaApp", targets: ["TabulaApp"]),
        .library(name: "TabulaWidgets", targets: ["TabulaWidgets"]),
    ],
    dependencies: [
        .package(path: "Packages/TimetableCore"),
        .package(path: "Packages/TimetableUI"),
    ],
    targets: [
        .target(
            name: "TabulaApp",
            dependencies: [
                .product(name: "TimetableCore", package: "TimetableCore"),
                .product(name: "TimetableUI", package: "TimetableUI"),
            ],
            path: "App/Sources",
            swiftSettings: appSwiftSettings
        ),
        .target(
            name: "TabulaWidgets",
            dependencies: [
                .product(name: "TimetableCore", package: "TimetableCore"),
                .product(name: "TimetableUI", package: "TimetableUI"),
            ],
            path: "WidgetExtension/Sources",
            swiftSettings: crossImportOverlays + intentDefines,
            // xtool links the extension with `-e _NSExtensionMain` (like Xcode's LD_ENTRY_POINT), so nothing
            // references the widget's Swift `_main` (generated by `@main struct TabulaWidgetBundle`). Under
            // xtool 1.20.1 + SwiftBuild + ld64.lld the package objects are then never loaded: the appex had NO
            // __text section, and xtool's signer (zsign) aborted with "Can't find free space of LoadCommands
            // for CodeSignature!". VERIFIED 2026-10-06 by relinking: with `-u _main` the appex grows from
            // 49 KB to 321 KB and contains __text + __swift5_entry (which the extension runtime uses to find
            // the @main type). Applies to the xtool path only; Xcode links the target's objects directly.
            linkerSettings: [.unsafeFlags(["-Xlinker", "-u", "-Xlinker", "_main"])]
        ),
    ],
    swiftLanguageModes: [.v6]
)
